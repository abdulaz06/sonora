#!/usr/bin/env node
// THIRD-PARTY-NOTICES.md: the licenses of everything the desktop app and the
// website bundle (Rust crates compiled into sonora.exe and the WebAssembly
// analyser, the JavaScript packages bundled into the app, the fonts). Run after
// dependency changes:  node scripts/third-party-notices.mjs
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OWN = new Set(['sonora', 'sonora-dsp', 'sonora-dsp-wasm']);

/** Normal (non-dev) dependencies reachable from our crates for a target. */
function crates(platform) {
  const m = JSON.parse(execFileSync('cargo', ['metadata', '--format-version', '1', '--filter-platform', platform], { cwd: ROOT, maxBuffer: 64 << 20 }).toString());
  const pk = new Map(m.packages.map((p) => [p.id, p]));
  const nodes = new Map(m.resolve.nodes.map((n) => [n.id, n]));
  const seen = new Set();
  const stack = m.packages.filter((p) => OWN.has(p.name)).map((p) => p.id);
  while (stack.length) {
    const id = stack.pop();
    if (seen.has(id)) continue;
    seen.add(id);
    for (const d of nodes.get(id)?.deps ?? []) {
      // Skip dev-only edges: nothing from them ships.
      if (d.dep_kinds.every((k) => k.kind === 'dev')) continue;
      stack.push(d.pkg);
    }
  }
  return [...seen].map((id) => pk.get(id)).filter((p) => p && !OWN.has(p.name));
}

const all = new Map();
for (const p of [...crates('x86_64-pc-windows-msvc'), ...crates('wasm32-unknown-unknown')]) all.set(`${p.name}@${p.version}`, p);
const list = [...all.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const licenseFiles = (dir) => (existsSync(dir) ? readdirSync(dir).filter((f) => /^(licen[cs]e|copying|notice|unlicense)/i.test(f)).sort() : []);
const copyrights = (text) => [...new Set(text.split(/\r?\n/).map((l) => l.trim()).filter((l) => /^(copyright\b|\(c\)\s*(\d{4}|[A-Z][a-z])|©)/i.test(l)
  && !/^\(c\) (you|under)\b/i.test(l) && !/copyright (notice|holder|owner|license|and|law|statement)s?\b/i.test(l) && !/\[yyyy\]|\{yyyy\}/i.test(l) && l.length < 200))];

const texts = new Map();   // license text → crates using exactly that text
const rows = [];
for (const p of list) {
  const dir = dirname(p.manifest_path);
  const files = licenseFiles(dir);
  const cr = new Set();
  for (const f of files) {
    const t = readFileSync(join(dir, f), 'utf8').replace(/\r\n/g, '\n').trim();
    for (const c of copyrights(t)) cr.add(c);
    const key = t;
    if (!texts.has(key)) texts.set(key, { file: f, crates: [] });
    texts.get(key).crates.push(`${p.name} ${p.version}`);
  }
  rows.push(`| ${p.name} | ${p.version} | ${p.license ?? p.license_file ?? 'see source'} | ${[...cr].join('; ').replace(/\|/g, '\\|') || (p.authors ?? []).join(', ').replace(/\|/g, '\\|')} |`);
}

const font = (n) => readFileSync(join(ROOT, 'src', 'assets', 'fonts', n), 'utf8').trim();
const npmPkg = (n) => JSON.parse(readFileSync(join(ROOT, 'node_modules', n, 'package.json'), 'utf8'));
const npmLicense = (n) => {
  const d = join(ROOT, 'node_modules', n);
  const f = licenseFiles(d)[0];
  return f ? readFileSync(join(d, f), 'utf8').trim() : '';
};
const js = ['@tauri-apps/api', '@tauri-apps/plugin-process', '@tauri-apps/plugin-updater'];

const out = [
  '# Third-party notices',
  '',
  'sonora is licensed under the PolyForm Noncommercial License 1.0.0 (see `LICENSE`). The desktop app and the website include the third-party software below; each part stays under its own license, reproduced here. Generated by `scripts/third-party-notices.mjs`.',
  '',
  'Software under the MPL-2.0 is used unmodified; its source code is available from crates.io (https://crates.io/crates/<name>) and the repositories listed there.',
  '',
  '## Fonts',
  '',
  '### Inter (SIL Open Font License 1.1)',
  '',
  '```', font('LICENSE-Inter.txt'), '```',
  '',
  '### IBM Plex Mono (SIL Open Font License 1.1)',
  '',
  '```', font('LICENSE-IBMPlexMono.txt'), '```',
  '',
  '## JavaScript packages bundled into the app',
  '',
  ...js.flatMap((n) => { const p = npmPkg(n); return [`### ${n} ${p.version} (${p.license})`, '', '```', npmLicense(n) || `${p.license}`, '```', '']; }),
  '## Rust crates (in sonora.exe and the WebAssembly analyser)',
  '',
  '| crate | version | license | copyright |',
  '|---|---|---|---|',
  ...rows,
  '',
  '## License texts',
  '',
  'Each distinct license text found in the crates above, with the crates that carry it.',
  '',
  ...[...texts.entries()].flatMap(([t, v]) => [`### ${v.file} — ${v.crates.join(', ')}`, '', '```', t, '```', '']),
];
writeFileSync(join(ROOT, 'THIRD-PARTY-NOTICES.md'), out.join('\n'));
console.log(`THIRD-PARTY-NOTICES.md: ${list.length} crates, ${texts.size} license texts, ${(out.join('\n').length / 1024).toFixed(0)} KB`);
